"""End-to-end plumbing check on SYNTHETIC videos. Proves the stages connect; says nothing about accuracy."""
import json
from pathlib import Path
import time

import numpy as np

from .config import ROOT, load_config, set_seed
from .synthetic import SMOKE_LAYOUT_REGEX, write_synthetic_videos


def run_smoke(workdir, config_path=None, log=print):
    config_path = config_path or ROOT / "configs" / "smoke.json"
    workdir = Path(workdir)
    # Never delete a caller-selected directory: it may contain real datasets or code.
    if workdir.exists() and any(workdir.iterdir()):
        raise FileExistsError(f'Smoke output directory is not empty: {workdir}. Choose a new directory.')
    data_root, artifacts = workdir / "synthetic_dataset", workdir / "artifacts"
    overrides = {"dataset": {"layout_regex": SMOKE_LAYOUT_REGEX,
                             "label_source": {"type": "filename_stem", "confirmed": True,
                                              "documentation": "SYNTHETIC SMOKE FIXTURE generated by research/synthetic.py; stems 0/5/10 are set by the generator, NOT by UTA-RLDD"}}}
    cfg = load_config(config_path, overrides)
    set_seed(cfg["seed"])
    steps = []

    def step(name, fn):
        started = time.perf_counter()
        out = fn()
        steps.append((name, round(time.perf_counter() - started, 1)))
        log(f"[smoke] {name}: ok ({steps[-1][1]} s)")
        return out

    from .baseline import train_baseline
    from .dataset import build_manifest, inspect_dataset, read_manifest, write_manifest
    from .evaluate import evaluate_run
    from .export import export_bundle
    from .extract import extract_all, load_cache
    from .heuristic import evaluate_heuristic
    from dms.features import frame_record
    from dms.learned import LearnedStatePredictor

    step("synthetic videos", lambda: write_synthetic_videos(data_root, seconds=12, fps=10))
    report = step("inspect", lambda: inspect_dataset(data_root, cfg))
    assert report["n_videos"] == 30, report["n_videos"]
    rows, meta = step("manifest", lambda: build_manifest(data_root, cfg, probe=True, log=lambda m: None))
    step("write manifest", lambda: write_manifest(rows, meta, artifacts / "manifest"))
    rows = read_manifest(artifacts / "manifest" / "manifest.csv")
    key, cache, failures = step("extract (real MediaPipe)", lambda: extract_all(rows, data_root, artifacts / "features", cfg, log=lambda m: None))
    assert not failures, failures
    step("heuristic replay", lambda: evaluate_heuristic(rows, cache, cfg, artifacts / "heuristic", log=lambda m: None))
    run = artifacts / "runs" / "smoke_baseline"
    manifest_meta = json.loads((artifacts / "manifest" / "manifest_meta.json").read_text())
    step("train baseline", lambda: train_baseline(cfg, rows, cache, run, manifest_meta["manifest_sha256"], synthetic=True, log=lambda m: None))
    step("evaluate val", lambda: evaluate_run(run, rows, cache, cfg, "val", log=lambda m: None))
    step("evaluate test", lambda: evaluate_run(run, rows, cache, cfg, "test", log=lambda m: None))
    dest = step("export (synthetic allowed)", lambda: export_bundle(run, workdir / "exported_bundle", allow_synthetic=True))
    predictor = LearnedStatePredictor.from_path(dest)
    arrays, _ = load_cache(cache, rows[0]["video_id"])
    states = collections_counter()
    for i in range(len(arrays["t"])):
        rec = {"detected": bool(arrays["detected"][i]), "valid": bool(arrays["valid"][i]), **{k: float(arrays[k][i]) for k in ("ear_l", "ear_r", "mar", "yaw", "pitch", "roll")}}
        states[predictor.update(float(arrays["t"][i]), rec)["state"]] += 1
    log(f"[smoke] live-predictor replay states: {dict(states)}")
    assert states["ok"] > 0, states
    log("[smoke] PLUMBING OK. Metrics from this run are on synthetic data and MUST NOT be quoted.")
    return 0


def collections_counter():
    import collections
    return collections.Counter()
